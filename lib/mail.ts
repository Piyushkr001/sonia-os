import "server-only";

import nodemailer from "nodemailer";

import type {
  ContactRequest,
} from "@/lib/contact-schema";

export function isContactEmailEnabled() {
  return process.env.CONTACT_EMAIL_ENABLED === "true";
}

export async function sendConnectionNotification(
  request: ContactRequest
) {
  if (!isContactEmailEnabled()) {
    return;
  }

  const host = process.env.SMTP_HOST;
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  const from = process.env.SMTP_FROM;

  const recipient =
    process.env.CONTACT_RECEIVER_EMAIL;

  const port = Number(
    process.env.SMTP_PORT || 587
  );

  if (
    !host ||
    !user ||
    !pass ||
    !from ||
    !recipient ||
    ![465, 587, 2525].includes(port)
  ) {
    throw new Error(
      "SMTP configuration is incomplete or invalid."
    );
  }

  const transporter = nodemailer.createTransport({
    host,
    port,

    secure: port === 465,

    requireTLS: port !== 465,

    auth: {
      user,
      pass,
    },

    connectionTimeout: 10000,
    greetingTimeout: 10000,
    socketTimeout: 15000,
  });

  const intentLabel = request.intent
    .replaceAll("_", " ")
    .toUpperCase();

  const info = await transporter.sendMail({
    from,

    // Recipient is controlled by the server,
    // not by the visitor.
    to: recipient,

    replyTo: request.email,

    subject:
      `SONIA.OS | New Connection Request | ${intentLabel}`,

    text: `
SONIA.OS — CONNECTION PORTAL

A new connection request has been received.

Reference ID: ${request.requestId}
Connection Intent: ${intentLabel}

Name: ${request.name}
Email: ${request.email}
Organization: ${request.organization || "Not provided"}

Message:
${request.message}

The visitor agreed to be contacted regarding this request.

This notification was generated by SONIA.OS.
    `.trim(),
  });

  if (!info.accepted.length) {
    throw new Error(
      "SMTP server did not accept the notification."
    );
  }

  return info.messageId;
}